export const researchById = (id: string) => RESEARCH.find((r) => r.id === id);

export function isAvailable(node: ResearchNode, done: string[]) {
  return node.requires.every((r) => done.includes(r));
}

export function researchModifiers(done: string[]) {
  return {
    coverageCeiling: 0.75 + (done.includes('ftth') ? 0.15 : 0) + (done.includes('gpon') ? 0.1 : 0),
    accessCostMul: done.includes('gpon') ? 0.75 : 1,
    accessCapacityMul: done.includes('gpon') ? 1.2 : 1,
    linkCapacityMul: done.includes('fiber10g') ? 1.3 : 1,
    maxLinkTier: done.includes('fiber10g') ? 3 : 2,
    maxCoreTier: done.includes('backbone100g') ? 5 : 3,
    maxTowerTier: done.includes('mobile_5g') ? 4 : 2,
    transitCostMul: (done.includes('backbone100g') ? 0.85 : 1) * (done.includes('edge_compute') ? 0.7 : 1),
    incidentDurationMul: done.includes('noc') ? 0.8 : 1,
    incidentRateMul: (done.includes('noc') ? 0.85 : 1) * (done.includes('ai_ops') ? 0.75 : 1),
    ddosMul: done.includes('ddos_scrub') ? 0.5 : 1,
    lossImpactMul: done.includes('ai_ops') ? 0.75 : 1,
    mobileRevenueMul: done.includes('mobile_5g') ? 1.35 : 1,
    hasNoc: done.includes('noc'),
    hasAutoDispatch: done.includes('auto_dispatch'),
    hasEnterprise: done.includes('sla_desk'),
    hasMobile: done.includes('mobile_4g'),
    hasAutoBalance: done.includes('ai_ops'),
  };
}

export type ResearchMods = ReturnType<typeof researchModifiers>;
